export type CatalogKind = 'food' | 'salon' | 'gym' | 'clinic' | 'retail' | 'shop';
export type FulfillmentMode = 'DineIn' | 'Delivery' | 'Pickup';

export function catalogKind(type?: string | null): CatalogKind {
  const text = (type || '').toLowerCase();
  if (/salon|spa|beauty|barber|parlour|parlor|\bhair\b/.test(text)) return 'salon';
  if (/gym|fitness/.test(text)) return 'gym';
  if (/clinic|health|hospital|dental|doctor|pharma/.test(text)) return 'clinic';
  if (/retail|boutique|\bstore\b/.test(text)) return 'retail';
  if (/restaurant|cafe|coffee|bakery|\bfood\b|dhaba|\bbar\b|kitchen/.test(text)) return 'food';
  return 'shop';
}

